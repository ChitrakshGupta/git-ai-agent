"""
Turns a Review into a GitHub pull request review: summary body + inline comments.
"""

import logging

from app.services import diff_utils
from app.services.github_client import GitHubClient, GitHubError
from app.services.schemas import Finding, Review

logger = logging.getLogger("publisher")

ICON = {"bug": "🐛", "risk": "⚠️", "missing_test": "🧪", "style": "🎨"}
LABEL = {"bug": "Bug", "risk": "Risk", "missing_test": "Missing test", "style": "Style"}
SEV = {"high": "🔴 high", "medium": "🟡 medium", "low": "🟢 low"}


def _finding_md(f: Finding, with_location: bool) -> str:
    loc = f" — `{f.file}{':' + str(f.line) if f.line else ''}`" if with_location else ""
    text = f"{ICON[f.category.value]} **{LABEL[f.category.value]} ({SEV[f.severity.value]}): {f.title}**{loc}\n\n{f.explanation}"
    if f.suggestion:
        text += f"\n\n**Suggestion:** {f.suggestion}"
    return text


def build_review_payload(review: Review, files: dict[str, dict]) -> tuple[str, list[dict]]:
    """Return (body, inline_comments). Findings without a valid diff line go in the body."""
    inline, body_findings = [], []
    for f in review.findings:
        patch = files.get(f.file, {}).get("patch")
        if f.line is not None and f.line in diff_utils.commentable_lines(patch):
            inline.append({"path": f.file, "line": f.line, "side": "RIGHT", "body": _finding_md(f, False)})
        else:
            body_findings.append(f)

    counts = {c: sum(1 for f in review.findings if f.category.value == c) for c in ICON}
    lines = [
        "## 🤖 AI Code Review",
        "",
        review.summary,
        "",
        f"**Overall risk:** {SEV[review.risk_level.value]}  ·  "
        + "  ·  ".join(f"{ICON[c]} {LABEL[c]}: {n}" for c, n in counts.items()),
    ]
    if body_findings:
        lines += ["", "### File-level findings", ""]
        lines += [_finding_md(f, True) + "\n" for f in body_findings]
    if inline:
        lines += ["", f"_{len(inline)} inline comment(s) on the diff._"]
    lines += ["", "---", "_Generated by the PR Review Agent (Gemini). Verify before acting on it._"]
    return "\n".join(lines), inline


async def publish_review(gh: GitHubClient, repo: str, number: int, head_sha: str, review: Review) -> str:
    """Post the review on the PR and return its URL."""
    files = {f["filename"]: f for f in await gh.list_pr_files(repo, number)}
    body, inline = build_review_payload(review, files)
    try:
        result = await gh.create_review(repo, number, head_sha, body, inline)
    except GitHubError as exc:
        if exc.status != 422 or not inline:
            raise
        # 422 usually means one inline comment points at a line GitHub won't accept
        # (e.g. the PR moved on). Fall back to a single review with everything in the body.
        logger.warning("Inline review rejected (%s); posting body-only review", exc)
        all_in_body = Review(
            summary=review.summary,
            risk_level=review.risk_level,
            findings=[f.model_copy(update={"line": None}) for f in review.findings],
        )
        body, _ = build_review_payload(all_in_body, {})
        result = await gh.create_review(repo, number, head_sha, body, [])
    return result.get("html_url", "")
